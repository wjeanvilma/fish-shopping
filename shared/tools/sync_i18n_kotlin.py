#!/usr/bin/env python3
"""Regenerate UiStrings.kt and ContentStrings.kt maps from shared/i18n JSON bundles."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LOCALES = ["en", "es", "pt", "fr", "ht", "it", "ca", "ru"]
LOCALE_CONST = {
    "en": "EN",
    "es": "ES",
    "pt": "PT",
    "fr": "FR",
    "ht": "HT",
    "it": "IT",
    "ca": "CA",
    "ru": "RU",
}


def esc(s: str) -> str:
    return (
        s.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "")
        .replace("\t", "\\t")
        .replace("$", "\\$")
    )


def load_strings(kind: str, locale: str) -> dict[str, str]:
    path = ROOT / "shared" / "i18n" / f"{kind}-strings.{locale}.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    return dict(sorted(data["strings"].items()))


def map_block(const_name: str, strings: dict[str, str]) -> str:
    lines = [f"    private val {const_name} = mapOf("]
    items = list(strings.items())
    for i, (key, value) in enumerate(items):
        comma = "," if i < len(items) - 1 else ""
        lines.append(f'        "{esc(key)}" to "{esc(value)}"{comma}')
    lines.append("    )")
    return "\n".join(lines)


def write_ui_strings() -> None:
    maps = {loc: load_strings("ui", loc) for loc in LOCALES}
    en_keys = set(maps["en"])
    for loc, strings in maps.items():
        if set(strings) != en_keys:
            missing = sorted(en_keys - set(strings))
            extra = sorted(set(strings) - en_keys)
            raise SystemExit(f"ui key mismatch {loc}: missing={missing[:5]} extra={extra[:5]}")

    map_sections = "\n\n".join(map_block(LOCALE_CONST[loc], maps[loc]) for loc in LOCALES)
    bundles = ",\n".join(f'        "{loc}" to {LOCALE_CONST[loc]}' for loc in LOCALES)

    header = """package com.willio.jeanvilma.fishshopping.core.i18n

import com.willio.jeanvilma.fishshopping.core.ship.I18nScaffold

/**
 * UI chrome string resolver (en + es + pt + fr + ht + it + ca + ru).
 * Generated from shared/i18n/ui-strings.*.json via shared/tools/sync_i18n_kotlin.py.
 * Presentation-only.
 */
object UiStrings {
    const val DEFAULT_LOCALE = I18nScaffold.DEFAULT_LOCALE
    const val SECOND_LOCALE = I18nScaffold.SECOND_LOCALE

    val SUPPORTED_LOCALES: List<String> = I18nScaffold.SUPPORTED_LOCALES
    val KEYS: Set<String> get() = EN.keys

"""
    footer = f"""
    private val bundles = mapOf(
{bundles},
    )

    @Volatile
    private var activeLocale: String = DEFAULT_LOCALE

    fun isSupported(locale: String?): Boolean =
        locale != null && locale in SUPPORTED_LOCALES

    fun resolveLocale(preferred: String? = null): String {{
        if (isSupported(preferred)) return preferred!!
        return DEFAULT_LOCALE
    }}

    fun getLocale(): String = activeLocale

    fun setLocale(locale: String): String {{
        activeLocale = resolveLocale(locale)
        return activeLocale
    }}

    fun t(key: String, params: Map<String, Any> = emptyMap(), locale: String = activeLocale): String {{
        val primary = bundles[resolveLocale(locale)]?.get(key)
        val fallback = EN[key]
        var out = primary ?: fallback ?: key
        for ((k, v) in params) {{
            out = out.replace("{{$k}}", v.toString())
        }}
        return out
    }}

    fun keyCount(locale: String = DEFAULT_LOCALE): Int =
        bundles[resolveLocale(locale)]?.size ?: 0
}}
"""
    # footer still has doubled braces from f-string for Kotlin {$k}
    footer = footer.replace('out.replace("{{$k}}", v.toString())', 'out.replace("{$k}", v.toString())')

    out = ROOT / "game-core/src/main/kotlin/com/willio/jeanvilma/fishshopping/core/i18n/UiStrings.kt"
    out.write_text(header + map_sections + "\n" + footer, encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)} ({len(en_keys)} keys × {len(LOCALES)} locales)")


def locale_map_file(object_name: str, strings: dict[str, str]) -> str:
    """One locale per file so ContentStrings avoids JVM MethodTooLargeException."""
    items = list(strings.items())
    lines = [
        "package com.willio.jeanvilma.fishshopping.core.i18n",
        "",
        "/** Generated by shared/tools/sync_i18n_kotlin.py — do not edit by hand. */",
        f"internal object {object_name} {{",
        "    val MAP: Map<String, String> = mapOf(",
    ]
    for i, (key, value) in enumerate(items):
        comma = "," if i < len(items) - 1 else ""
        lines.append(f'        "{esc(key)}" to "{esc(value)}"{comma}')
    lines.append("    )")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def write_content_strings() -> None:
    maps = {loc: load_strings("content", loc) for loc in LOCALES}
    en_keys = set(maps["en"])
    for loc, strings in maps.items():
        if set(strings) != en_keys:
            missing = sorted(en_keys - set(strings))
            extra = sorted(set(strings) - en_keys)
            raise SystemExit(f"content key mismatch {loc}: missing={missing[:5]} extra={extra[:5]}")

    i18n_dir = ROOT / "game-core/src/main/kotlin/com/willio/jeanvilma/fishshopping/core/i18n"
    for loc in LOCALES:
        const = LOCALE_CONST[loc]
        obj = f"ContentStrings{const}"
        path = i18n_dir / f"{obj}.kt"
        path.write_text(locale_map_file(obj, maps[loc]), encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)} ({len(maps[loc])} keys)")

    bundles = ",\n".join(
        f'        "{loc}" to ContentStrings{LOCALE_CONST[loc]}.MAP' for loc in LOCALES
    )
    facade = f"""package com.willio.jeanvilma.fishshopping.core.i18n

/**
 * Content-pack display-name overlays (en + es + pt + fr + ht + it + ca + ru).
 * Locale maps live in ContentStringsXX.kt (generated) to stay under JVM method size limits.
 * Generated from shared/i18n/content-strings.*.json via shared/tools/sync_i18n_kotlin.py.
 */
object ContentStrings {{
    const val DEFAULT_LOCALE = UiStrings.DEFAULT_LOCALE

    private val EN = ContentStringsEN.MAP

    val KEYS: Set<String> get() = EN.keys

    private val bundles = mapOf(
{bundles},
    )

    fun t(id: String, fallback: String = id, locale: String = UiStrings.getLocale()): String {{
        val primary = bundles[UiStrings.resolveLocale(locale)]?.get(id)
        val english = EN[id]
        return primary ?: english ?: fallback
    }}

    fun keyCount(locale: String = DEFAULT_LOCALE): Int =
        bundles[UiStrings.resolveLocale(locale)]?.size ?: 0
}}
"""
    out = i18n_dir / "ContentStrings.kt"
    out.write_text(facade, encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)} facade ({len(en_keys)} keys × {len(LOCALES)} locales)")


def main() -> None:
    write_ui_strings()
    write_content_strings()


if __name__ == "__main__":
    main()
